  " * `@mohsinonxrm/dataverse-sdk-core` (#254), as the ones in",
  " * `@mohsinonxrm/dataverse-sdk-entities-runtime` do, so both code generators write the same",
  " * literals.",
  " */",
  "import {",
  "  odataLiteral,",
