  "export type ParameterKind = ODataParameterKind;",
  "",
  "/**",
  " * The path of one record, `<entity set>(<id>)`, for binding an operation to it.",
  " *",
  " * @throws DataverseInvalidRequestError when the reference has no `entitySetName`.",
