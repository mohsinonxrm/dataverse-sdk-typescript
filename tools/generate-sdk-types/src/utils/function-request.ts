type AliasKind = "entityReference" | "complex" | "scalar";

/**
 * How a function parameter is written as a parameter-alias value:
 * an `@odata.id` reference, JSON (complex types), or an OData literal (primitives and enums).
 */
function aliasKind(csdl: CsdlSchema, paramType: string): AliasKind {
  const isEntityRef =
    paramType === "mscrm.crmbaseentity" || csdlTypeToTs(paramType, false) === "EntityReference";
  if (isEntityRef) return "entityReference";
  const isPrimitive = paramType.startsWith("Edm.");
  const isEnum = csdl.enumTypes.some(
    (et) => `${et.namespace}.${et.name}` === paramType || `mscrm.${et.name}` === paramType
  );
  if (!isPrimitive && !isEnum && paramType.includes(".")) return "complex";
  return "scalar";
}

/** The generated enum a parameter type names, if it is one (`mscrm.EntityFilters`). */
function enumTypeName(csdl: CsdlSchema, paramType: string): string | undefined {
  return csdl.enumTypes.find(
    (et) => `${et.namespace}.${et.name}` === paramType || `mscrm.${et.name}` === paramType
  )?.name;
}

/**
 * TypeScript type of a function parameter: an enum also takes a member name (#67), and a
 * date-time also takes a `Date` (#68).
 */
export function functionParameterTsType(csdl: CsdlSchema, paramType: string): string {
  const polymorphic = polymorphicParameterType(csdl, paramType);
  if (polymorphic) return polymorphic.tsType;
  const enumName = enumTypeName(csdl, paramType);
  if (enumName) return `${enumName} | keyof typeof ${enumName}`;
  if (paramType === "Edm.DateTimeOffset" || paramType === "Edm.Date") return "string | Date";
  return csdlTypeToTs(paramType, true);
}

/**
 * The `formatParameterAlias(...)` call for a parameter value (`this.parameters.X`):
 *
 * - a record reference: `{"@odata.id": "<entity set>(<id>)"}`; throws without an entity set (#72);
 * - a complex type or a collection: JSON, with its enum members as names (`enumBody`, as action
 *   bodies have them, #232): Dataverse reads an enum in a JSON parameter only by name (#358);
 * - a primitive or an enum: the OData literal of its type (quoted string, bare GUID or date, enum
 *   literal; #22, #67, #68).
 *
 * @param scope - Whose `internal/enumBody.ts` tables the generated code calls (#358).
 */
function aliasValue(
  csdl: CsdlSchema,
  value: string,
  paramType: string,
  scope: EnumBodyScope
): { code: string; usesEnumBody: boolean } {
  const kind = aliasKind(csdl, paramType);
  if (kind === "entityReference") {
    return {
      code: `formatParameterAlias(${value}, '${paramType}', 'EntityType')`,
      usesEnumBody: false,
    };
  }
  if (kind === "complex") {
    const enumType = bodyEnumType(csdl, paramType, scope);
    const json = enumType ? `enumBody(${value}, ${JSON.stringify(enumType)})` : value;
    const isEntity = csdl.entityTypes.some((et) => `mscrm.${et.name}` === paramType);
    const odataKind = isCollectionType(paramType)
      ? "Collection"
      : isEntity
        ? "EntityType"
        : "ComplexType";
    return {
      code: `formatParameterAlias(${json}, '${paramType}', '${odataKind}')`,
      usesEnumBody: enumType !== undefined,
    };
  }
  const enumKind = enumTypeName(csdl, paramType) ? `, 'EnumerationType'` : "";
  return { code: `formatParameterAlias(${value}, '${paramType}'${enumKind})`, usesEnumBody: false };
}

/** A function's constructor arguments, and what their types import. */
export interface FunctionSignature {
  /**
   * The record or entity set a bound function runs on (in the URL), then one entry per CSDL
   * parameter, which go in one parameters object (#96).
   */
  args: OperationArgument[];
  /** Types the parameters use, from `./types/index.js`. */
  typeImports: string[];
  /** A parameter is an `EntityReference`. */
  needsEntityReference: boolean;
}

/**
 * The constructor arguments of a function class.
 *
 * @param recordIdName - Name of the record-id argument of a function bound to one record, from its
 *   table (`systemuser` → `systemuserId`).
 */
export function functionSignature(
  csdl: CsdlSchema,
  func: CsdlFunction,
  recordIdName: (table: string) => string
): FunctionSignature {
  // A function has no body: its parameters import their types, and a single entity reference
  // (not a Collection) imports EntityReference
  const { typeImports } = parameterImports(csdl, func);
  const needsEntityReference = func.parameters.some(
    (p) => !isCollectionType(p.type) && csdlTypeToTs(p.type, false) === "EntityReference"
  );
  const args = operationArguments(csdl, func, recordIdName, (type) =>
    functionParameterTsType(csdl, type)
  );
  return { args, typeImports, needsEntityReference };
}

/** The `toRequestInformation` method of a function, and the helpers it calls. */
export interface FunctionRequest {
  code: string;
  /** The code calls `formatParameterAlias` (from {@link ODATA_LITERAL_MODULE}). */
  usesAliasLiteral: boolean;
  /** The code calls `enumBody` (from `internal/enumBody`). */
  usesEnumBody: boolean;
}

/**
 * The `toRequestInformation` method of a function, or of a function-backed message: `GET` the
 * function on its record, entity set or the service root (as an action's URL), with one parameter
 * alias per parameter that is set.
 *
 * @param args - The constructor's arguments, binding first, as the class declares them.
 * @param source - Where the parameter values are read: `this.parameters` (functions package) or
 *   `this.Parameters` (messages).
 * @param scope - The `enumBody` tables of the package the code goes into.
 */
export function functionRequestMethod(
  csdl: CsdlSchema,
  func: CsdlFunction,
  args: readonly OperationArgument[],
  source: string,
  scope: EnumBodyScope
): FunctionRequest {
  const uses = { aliasLiteral: false, enumBody: false };

  /** The statements that add one parameter alias, when the parameter is set. */
  const aliasStatement = (name: string, alias: string, paramType: string): string => {
    const value = aliasValue(csdl, `${source}.${name}`, paramType, scope);
    uses.aliasLiteral = true;
    if (value.usesEnumBody) uses.enumBody = true;
    let statement = `    if (${source}.${name} !== undefined) {\n`;
    statement += `      aliases.push(\`${name}=${alias}\`);\n`;
    statement += `      params.append('${alias}', ${value.code});\n`;
    statement += `    }\n`;
    return statement;
  };

  /** The parameter aliases (the binding isn't one). */
  const aliasStatements = (): string => {
    const queryParams = args.filter((p) => !p.isBinding);
    if (queryParams.length === 0) return "";
    let out = `    // Build query parameters using parameter aliases\n`;
    out += `    const params = new URLSearchParams();\n`;
    out += `    const aliases: string[] = [];\n`;
    let aliasIndex = 1;
    for (const param of queryParams) {
      const alias = `@p${String(aliasIndex++)}`;
      const paramType = func.parameters.find((p) => p.name === param.tsName)?.type ?? "";
      out += aliasStatement(param.tsName, alias, paramType);
    }
    out += `    if (aliases.length > 0) {\n`;
    out += `      url += \`(\${aliases.join(',')})?\${params.toString()}\`;\n`;
    out += `    }\n\n`;
    return out;
  };

  // The URL is built as for an action (`let`: the aliases follow), then `GET` with JSON accepted
  const statements = operationUrlStatement(csdl, func, args, "function") + aliasStatements();
  return {
    code: requestInformationMethod(statements, "GET"),
    usesAliasLiteral: uses.aliasLiteral,
    usesEnumBody: uses.enumBody,
  };
}

/** The import lines of the helpers a function's request calls (`enumBody`, `formatParameterAlias`). */
export function functionHelperImports(request: FunctionRequest): string {
  let code = "";
  if (request.usesEnumBody)
    code += `import { enumBody } from './internal/${ENUM_BODY_MODULE}.js';\n`;
  if (request.usesAliasLiteral) {
    code += `import { formatParameterAlias } from './${ODATA_LITERAL_MODULE}.js';\n`;
  }
  return code;
}
