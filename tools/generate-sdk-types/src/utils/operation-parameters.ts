/**
 * Options-object constructors for the generated operations (#96).
 *
 * The constructors took every CSDL parameter positionally, in CSDL order:
 * `new RetrieveEntityFunction(EntityFilters, LogicalName, MetadataId, RetrieveAsIfPublished)`
 * puts `LogicalName` before `MetadataId`, so swapping them was a silent bug, and
 * `ImportSolutionAction` took 17 arguments. Each operation with parameters now has a
 * `<Class>Parameters` interface keyed by the CSDL parameter names, and the constructor takes one
 * object of that type:
 *
 *     new ImportSolutionAction({ CustomizationFile, ImportJobId, OverwriteUnmanagedCustomizations: true, PublishWorkflows: false })
 *
 * A parameter the CSDL declares `Nullable="false"` is required; any other is optional, and an
 * `undefined` one is left out of the request (the action body, or the function's URL aliases).
 *
 * The record or entity set a bound operation runs on isn't a parameter of the request: it's in the
 * URL. It stays a separate first argument, before the parameters object:
 * `new AddItemCampaign_campaignAction(campaignId, { EntityId, EntityName })`.
 */

import { ENTITY_SET_PARAM } from "./binding.js";
import { extractEntityTypeName } from "./typescript-writer.js";

/**
 * The class doc lines that say what a bound operation's first argument is: the entity set
 * (`Collection(mscrm.crmbaseentity)`) or the id of the record.
 *
 * @param bindingArgument - Name of the binding argument, if the constructor has one.
 * @param bindingType - CSDL type of the binding parameter.
 */
export function bindingDoc(bindingArgument: string | undefined, bindingType?: string): string {
  if (!bindingArgument) return "";
  if (bindingArgument === ENTITY_SET_PARAM) {
    return ` *\n * The first argument is the entity set to call it on, for example "accounts".\n`;
  }
  const table = bindingType ? extractEntityTypeName(bindingType) : "bound";
  return ` *\n * The first argument is the id of the ${table} record to call it on.\n`;
}

/** One operation parameter, as it appears in the `<Class>Parameters` interface. */
export interface OperationParameter {
  /** The CSDL parameter name: the interface property, the body key and the URL alias name. */
  name: string;
  /** TypeScript type. */
  type: string;
  /** The CSDL doesn't declare `Nullable="false"`, so the parameter may be left out. */
  optional: boolean;
}

/** Name of the parameters interface of an operation class (`ImportSolutionActionParameters`). */
export function parametersInterfaceName(className: string): string {
  return `${className}Parameters`;
}

/**
 * The `<Class>Parameters` interface, one property per parameter in CSDL order.
 *
 * @param label - What the operation is, for the doc comment (`ImportSolution action`).
 */
export function parametersInterface(
  interfaceName: string,
  label: string,
  params: readonly OperationParameter[]
): string {
  let code = `/**\n`;
  code += ` * Parameters of the ${label}, by their CSDL names. A parameter the CSDL declares\n`;
  code += ` * nullable is optional, and left out of the request when it's undefined.\n`;
  code += ` */\n`;
  code += `export interface ${interfaceName} {\n`;
  for (const p of params) code += `  ${p.name}${p.optional ? "?" : ""}: ${p.type};\n`;
  code += `}\n`;
  return code;
}

/**
 * The constructor's parameters argument: `parameters: X`, or `parameters: X = {}` when every
 * parameter is optional, so the argument can be left out.
 */
export function parametersArgument(
  modifier: string,
  interfaceName: string,
  params: readonly OperationParameter[]
): string {
  const prefix = modifier ? `${modifier} ` : "";
  const optional = params.every((p) => p.optional);
  return `${prefix}parameters: ${interfaceName}${optional ? " = {}" : ""}`;
}

