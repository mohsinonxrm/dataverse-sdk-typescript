/**
 * The `requestBody({...})` expression for an action's parameters, read from `source`
 * (`this.parameters`, or `this.Parameters` in a message).
 *
 * @param enumTypeOf - The enum or complex type to pass to `enumBody` for a parameter, if any (#232).
 */
export function requestBodyExpression(
  source: string,
  params: readonly OperationParameter[],
  enumTypeOf: (name: string) => string | undefined
): string {
  let code = `requestBody({\n`;
  for (const p of params) {
    const enumType = enumTypeOf(p.name);
    const value = enumType
      ? `enumBody(${source}.${p.name}, ${JSON.stringify(enumType)})`
      : `${source}.${p.name}`;
    code += `      ${p.name}: ${value},\n`;
  }
  code += `    })`;
  return code;
}
