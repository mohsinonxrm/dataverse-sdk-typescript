/**
 * Entity-typed parameters of actions and messages (#74).
 *
 * In a request body the Web API reads an entity parameter as an entity: its columns,
 * `@odata.type` (which table), and `<lookup>@odata.bind` to set a lookup. A reference is the same
 * shape with only the primary key. `Merge`'s `UpdateContent` (`mscrm.crmbaseentity`) carries the
 * new column values, and `WinOpportunity`'s `OpportunityClose` sets `opportunityid@odata.bind`, so
 * typing these as `EntityReference` or as the read shape (`_opportunityid_value`) forced `as any`.
 */
import type { CsdlSchema } from "../parsers/csdl-types.js";
import { SYSTEM_ENTITIES } from "./polymorphism.js";

/** Name of the generated module, under `types/`. */
export const ENTITY_PAYLOAD_MODULE = "EntityPayload";

/** Source of the generated `types/EntityPayload.ts`. */
export const ENTITY_PAYLOAD_SOURCE = `/**
 * Entity payloads for entity-typed action parameters.
 * Generated by tools/generate-sdk-types. Do not edit by hand.
 */

/**
 * A record of table \`T\` in a request body: any of its columns, \`@odata.type\`, and lookups set with
 * \`<navigation property>@odata.bind\`.
 *
 * @example
 * const close: EntityPayload<opportunityclose> = {
 *   "@odata.type": "Microsoft.Dynamics.CRM.opportunityclose",
 *   subject: "Won",
 *   "opportunityid@odata.bind": "/opportunities(<id>)",
 * };
 */
export type EntityPayload<T extends object> = Partial<T> & {
  /** The table, as \`Microsoft.Dynamics.CRM.<logical name>\`. */
  "@odata.type"?: string;
  /** Set a lookup: \`"parentaccountid@odata.bind": "/accounts(<id>)"\`. */
  [lookup: \`\${string}@odata.bind\`]: string | null;
};

/**
 * A record of any table (a \`crmbaseentity\` parameter, such as \`Merge\`'s \`UpdateContent\`):
 * \`@odata.type\` names the table, and the other properties are its columns and
 * \`<lookup>@odata.bind\` values.
 *
 * @example
 * const updateContent: AnyEntityPayload = {
 *   "@odata.type": "Microsoft.Dynamics.CRM.account",
 *   description: "Merged",
 * };
 */
export interface AnyEntityPayload {
  /** The table, as \`Microsoft.Dynamics.CRM.<logical name>\`. */
  "@odata.type": string;
  [property: string]: unknown;
}
`;

/** TypeScript type of an entity-typed action parameter, and the payload types it uses. */
export interface EntityParameterType {
  tsType: string;
  /** Entity interface from `types/` (the table), when the parameter names one. */
  entity?: string;
  /** Payload types from `types/EntityPayload.ts`. */
  payload: Array<"EntityPayload" | "AnyEntityPayload">;
}

function localName(type: string): string {
  return type.replace(/^Microsoft\.Dynamics\.CRM\.|^mscrm\./, "");
}

/**
 * The parameter type for an entity-typed (`mscrm.<entity>` or `Collection(mscrm.<entity>)`) body
 * parameter, or `undefined` for any other type.
 * - `crmbaseentity` (any table): `EntityReference | AnyEntityPayload`;
 * - a table: `EntityReference | EntityPayload<table>` (a reference is a payload with only the key);
 * - a collection of a table: `(EntityReference | EntityPayload<table>)[]`
 *   (`Collection(crmbaseentity)` keeps `Record<string, unknown>[]`).
 *
 * `principal` and the other abstract system types stay `EntityReference`: they are always
 * references to a user or team.
 */
export function entityParameterType(
  csdl: CsdlSchema,
  csdlType: string
): EntityParameterType | undefined {
  const collection = csdlType.startsWith("Collection(");
  const name = localName(collection ? csdlType.slice(11, -1) : csdlType);
  if (name === "crmbaseentity") {
    return collection
      ? undefined
      : { tsType: "EntityReference | AnyEntityPayload", payload: ["AnyEntityPayload"] };
  }
  if (SYSTEM_ENTITIES.includes(name.toLowerCase())) return undefined;
  const isEntity = csdl.entityTypes.some(
    (t) => t.name === name && t.namespace === "Microsoft.Dynamics.CRM"
  );
  if (!isEntity) return undefined;
  return collection
    ? {
        tsType: `(EntityReference | EntityPayload<${name}>)[]`,
        entity: name,
        payload: ["EntityPayload"],
      }
    : {
        tsType: `EntityReference | EntityPayload<${name}>`,
        entity: name,
        payload: ["EntityPayload"],
      };
}
